const fs = require("fs");
const path = require("path");

/**
 * Write the constructor-args file for AgentMintFactory verification.
 *
 * Usage:
 *   node scripts/verify-args.js [chainId]
 *
 * Reads deployments/<chainId>.json and writes
 * deployments/verify-args-<chainId>-factory.js exporting
 * [implementation, token, agentId], for use with:
 *   npx hardhat verify --network bscTestnet \
 *     --constructor-args deployments/verify-args-97-factory.js <factory>
 *
 * Token, NFT implementation and MockAgentID take NO constructor args.
 */
const chainId = process.argv[2] || "97";
const dir = path.join(__dirname, "..", "deployments");
const deployment = JSON.parse(fs.readFileSync(path.join(dir, `${chainId}.json`), "utf8"));
const content =
  `// Constructor args for AgentMintFactory (chain ${chainId}).\n` +
  `// Generated by scripts/verify-args.js from deployments/${chainId}.json.\n` +
  `module.exports = [\n` +
  `  "${deployment.nftImplementation}", // implementation\n` +
  `  "${deployment.token}", // rewardToken\n` +
  `  "${deployment.agentId}", // agentId\n` +
  `];\n`;
const file = path.join(dir, `verify-args-${chainId}-factory.js`);
fs.writeFileSync(file, content);
console.log(`Wrote ${file}`);
console.log(content);
